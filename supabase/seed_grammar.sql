以 -o 结尾的形容词：阳性 -o，阴性 -a，复数加 -s（bueno→buena→buenos→buenas）。
以 -e 或辅音结尾的通常无性变化，只变数（grande→grandes）。
例句：
El coche es nuevo.（这辆车是新的。）
La casa es nueva.（这房子是新的。）
Las calles son grandes.（这些街道很宽。）$$),

