('简单过去时 vs 过去未完成时', 'B1', 21, $$indefinido 表示过去某个时刻完成的具体动作；imperfecto 表示过去持续的状态、习惯或背景。
常搭配：indefinido 用 ayer、el año pasado；imperfecto 用 cuando era niño、siempre。
例句：
Ayer fui al cine.（昨天我去了电影院。——完成）
Cuando era niño, iba al parque.（小时候我常去公园。——习惯）$$),

('现在完成时', 'B1', 22, $$pretérito perfecto = haber（现在时）+ 过去分词。
haber：he、has、ha、hemos、habéis、han。
过去分词：-ar→-ado（hablado），-er/-ir→-ido（comido、vivido）。
表示与现在有联系、或到目前仍有效的过去动作。
例句：
He comido mucho hoy.（我今天吃了很多。）
¿Has estado en España?（你去过西班牙吗？）$$),

('简单将来时', 'B1', 23, $$futuro simple 在动词原形后加词尾：-é、-ás、-á、-emos、-éis、-án（三类动词相同）。
不规则词干：tener→tendr-、venir→vendr-、hacer→har-、poder→podr-、querer→querr-、saber→sabr-、salir→saldr-、decir→dir-。
例句：
Mañana viajaré a Madrid.（明天我要去马德里。）
¿Qué harás este fin de semana?（这个周末你要做什么？）$$),

('条件式', 'B1', 24, $$condicional 词尾（加在动词原形后）：-ía、-ías、-ía、-íamos、-íais、-ían。
表示委婉请求、意愿，或过去将来。
例句：
Me gustaría un café, por favor.（我想要一杯咖啡，谢谢。）
¿Podrías ayudarme?（你能帮我吗？）$$),

('虚拟式现在时', 'B1', 25, $$presente de subjuntivo：-ar→-e 系列（hable），-er/-ir→-a 系列（coma、viva）。
用于表达愿望、请求、建议、怀疑，常见触发：querer que、esperar que、es importante que、para que。
例句：
Quiero que vengas a mi casa.（我希望你来我家。）
Es importante que estudies español.（学西语很重要。）$$),

('关系从句', 'B1', 26, $$关系代词 que（最常用）、donde（在……地方）、cuyo（其……的）、quien（某人）。
que 指人指物皆可，连接两个句子。
例句：
El libro que leo es interesante.（我正在读的书很有趣。）
La ciudad donde vivo es grande.（我住的城市很大。）$$),

('被动语态与无人称 se', 'B1', 27, $$被动语态：ser + 过去分词（性数一致）+ por（施动者）。
无人称 se：se + 第三人称单数动词，表示泛指“人们/有人”。
例句：
El edificio fue construido en 1990.（这栋楼建于 1990 年。）
Aquí se habla español.（这里讲西班牙语。）$$),

('过去完成时', 'B2', 28, $$pluscuamperfecto = haber（过去未完成时）+ 过去分词。
haber 的未完成时：había、habías、había、habíamos、habíais、habían。
表示“过去的过去”，即某一过去动作之前已完成的事。
例句：
Cuando llegué, ya había salido.（我到的时候，他已经走了。）$$),

('虚拟式过去时', 'B2', 29, $$imperfecto de subjuntivo 由第三人称复数简单过去时去掉 -ron，再加 -ra/-se 系列词尾：hablara/hablase、hablaras/hablases 等。
用法与虚拟式现在时一致，只是时态退回到过去。
例句：
Quería que vinieras.（我当时希望你来。）$$),

('虚拟式 vs 直陈式', 'B2', 30, $$直陈式陈述客观事实；虚拟式表达主观（愿望、情感、怀疑、评价、不确定）。
判断要点：表达事实用直陈，表达期望/情感/怀疑用虚拟。
例句：
Creo que viene.（我相信他会来。——肯定→直陈）
No creo que venga.（我不认为他会来。——否定/怀疑→虚拟）$$),

('间接引语', 'B2', 31, $$转述他人话语时，时态通常后退一级：
现在时→过去未完成时；将来时→条件式；现在完成/简单过去→过去完成时。
例句：
Dijo: "Voy al cine." → Dijo que iba al cine.（他说他要去电影院。）$$),

('高级虚拟式用法', 'C1', 32, $$虚拟式的高阶用法：各类连词（aunque、como si、antes de que、sin que）、感叹与祝愿（¡Que tengas suerte!）、无人称判断（es posible que）。
例句：
Aunque llueva, saldremos.（即使下雨，我们也要出门。）
¡Que tengas un buen día!（祝你今天愉快！）$$),

('复合条件句', 'C1', 33, $$真实条件（si + 现在时 → 将来/命令/现在时）：Si estudias, aprobarás.
与现在相反的假设（si + 虚拟式过去 → 条件式）：Si tuviera dinero, viajaría.
与过去相反的假设（si + 过去完成虚拟 → 复合条件式）：Si hubiera sabido, habría venido.
例句：
Si tengo tiempo, te llamo.（如果我有时间，就给你打电话。）
Si tuviera tiempo, viajaría.（要是我有时间，就会去旅行。）$$),

('惯用表达与习语', 'C1', 34, $$常用习语：estar en las nubes（心不在焉）、costar un ojo de la cara（贵得要命）、tener ganas de（想要做）、echar de menos（想念）、irse de vacaciones（去度假）。
例句：
Tengo ganas de aprender español.（我想学西语。）
Echo de menos a mi familia.（我想念家人。）$$)

