元音发音固定而清晰：a 如“啊”，e 如“诶”，i 如“衣”，o 如“哦”，u 如“乌”。
辅音要点：h 永远不发音（hola 读“欧拉”）；ñ 读“尼”（niño）；j 读“呵”（jugar）；c 在 e/i 前读“丝”，在 a/o/u 前读“克”；ll 多数地区读“耶”。
例句：
