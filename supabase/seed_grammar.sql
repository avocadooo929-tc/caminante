No comas tanto.（别吃这么多。）$$),

('比较级与最高级', 'A2', 17, $$比较级：más + 形容词 + que（更……）；menos + 形容词 + que（不如……）；tan + 形容词 + como（一样……）。
最高级：el/la + más + 形容词。
不规则：bueno→mejor，malo→peor，grande→mayor，pequeño→menor。
例句：
