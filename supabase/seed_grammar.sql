-ar 动词词尾：-é、-aste、-ó、-amos、-asteis、-aron。
-er/-ir 动词词尾：-í、-iste、-ió、-imos、-isteis、-ieron。
例：hablar→hablé；comer→comí；vivir→viví。
例句：
