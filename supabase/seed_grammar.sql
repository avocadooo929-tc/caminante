El niño juega en el parque.（男孩在公园里玩。）$$),

('名词的性与数', 'A1', 2, $$西班牙语名词有“性”（阳性/阴性）和“数”（单数/复数）。
一般以 -o 结尾为阳性（libro 书），以 -a 结尾为阴性（casa 房子）。
复数规则：元音结尾加 -s（libro→libros）；辅音结尾加 -es（ciudad→ciudades）；以 z 结尾把 z 改为 c 再加 -es（lápiz→lápices）。
注意例外：mano（手）是阴性，mapa（地图）、día（天）是阳性。
例句：
