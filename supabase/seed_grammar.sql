Es la ciudad más grande del país.（这是全国最大的城市。）$$),

('物主形容词', 'A2', 18, $$物主形容词：mi/mis（我的）、tu/tus（你的）、su/sus（他/她/您的）、nuestro/nuestra/nuestros/nuestras（我们的）、vuestro（你们的）。
置于名词前，与所修饰名词的数一致（nuestro/vuestro 还分性）。
